package com.example.myupnp.core

/**
 * 可收费功能清单（未来分级/付费的"边界"）
 * ------------------------------------------------------------------
 * 所有将来可能收费的功能都在这里登记一个 ID。
 * 业务代码只问 FeatureGate：这个功能现在能用吗？—— 不关心计费细节。
 *
 * 例：如果以后"曲库浏览 + 云转码 + 播放队列上限"收费，
 *     在需要校验的入口调 gate.canUse(FeatureId.X) 即可。
 */
enum class FeatureId {
    /** 基础功能占位。将来新增收费功能时在这里追加条目 */
    FREE_ALL,

    // ---- 将来可能收费的功能（示例，按需启用/移除） ----
    /** 播放队列/连播 */
    PLAYBACK_QUEUE,

    /** 设备管理上限（例如免费版只允许 5 台设备） */
    DEVICE_LIMIT,

    /** 高级 DLNA 功能（如转码/远程访问） */
    ADVANCED_DLNA,

    /** 去广告 */
    NO_ADS,
}
